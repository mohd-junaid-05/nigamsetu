import { PDFDocument, StandardFonts, rgb, PDFFont } from 'pdf-lib';

function wrapText(text: string, maxCharsPerLine: number): string[] {
  const result: string[] = [];
  const lines = text.split('\n');

  for (const rawLine of lines) {
    if (rawLine.length <= maxCharsPerLine) {
      result.push(rawLine);
      continue;
    }

    const words = rawLine.split(' ');
    let currentLine = '';

    for (const word of words) {
      if ((currentLine + (currentLine ? ' ' : '') + word).length <= maxCharsPerLine) {
        currentLine += (currentLine ? ' ' : '') + word;
      } else {
        if (currentLine) result.push(currentLine);
        currentLine = word;
      }
    }
    if (currentLine) {
      result.push(currentLine);
    }
  }

  return result;
}

export async function generateEscalationPdf(
  content: string,
  complaintId: string,
  authorityTitle?: string
): Promise<Uint8Array> {
  const pdfDoc = await PDFDocument.create();
  const fontRegular = await pdfDoc.embedFont(StandardFonts.Helvetica);
  const fontBold = await pdfDoc.embedFont(StandardFonts.HelveticaBold);

  const pageWidth = 595.28;
  const pageHeight = 841.89;
  const margin = 50;
  const contentWidth = pageWidth - margin * 2;
  const approxCharsPerLine = 75;

  let page = pdfDoc.addPage([pageWidth, pageHeight]);
  let y = pageHeight - margin;

  // Header banner
  page.drawRectangle({
    x: margin,
    y: y - 28,
    width: contentWidth,
    height: 32,
    color: rgb(0.12, 0.16, 0.22), // Dark Navy
  });

  page.drawText('NIGAMSETU CIVIC ESCALATION SYSTEM', {
    x: margin + 12,
    y: y - 16,
    size: 10,
    font: fontBold,
    color: rgb(1, 1, 1),
  });

  page.drawText(`REF: #${complaintId.slice(0, 8).toUpperCase()}`, {
    x: pageWidth - margin - 120,
    y: y - 16,
    size: 9,
    font: fontRegular,
    color: rgb(0.8, 0.85, 0.9),
  });

  y -= 48;

  // Process text lines
  const lines = wrapText(content, approxCharsPerLine);

  for (let i = 0; i < lines.length; i++) {
    const line = lines[i];

    // Check if new page is needed
    if (y < 60) {
      page = pdfDoc.addPage([pageWidth, pageHeight]);
      y = pageHeight - margin;

      // Repeat compact header on subsequent pages
      page.drawText(`NigamSetu Statutory Redressal • Complaint #${complaintId}`, {
        x: margin,
        y: y,
        size: 8,
        font: fontRegular,
        color: rgb(0.5, 0.5, 0.5),
      });
      y -= 24;
    }

    const isSubjectLine = line.toLowerCase().startsWith('subject:');
    const isHeading =
      line.startsWith('To,') ||
      line.startsWith('Complaint Reference:') ||
      line.startsWith('Complaint ID:') ||
      line.startsWith('Previous Actions Taken:') ||
      line.startsWith('Enclosures:');

    if (isSubjectLine) {
      page.drawText(line, {
        x: margin,
        y,
        size: 10.5,
        font: fontBold,
        color: rgb(0.08, 0.1, 0.15),
      });
      y -= 18;
    } else if (isHeading) {
      page.drawText(line, {
        x: margin,
        y,
        size: 10,
        font: fontBold,
        color: rgb(0.15, 0.2, 0.25),
      });
      y -= 15;
    } else if (line.trim() === '') {
      y -= 10;
    } else {
      page.drawText(line, {
        x: margin,
        y,
        size: 9.5,
        font: fontRegular,
        color: rgb(0.2, 0.22, 0.25),
      });
      y -= 14;
    }
  }

  // Footer on last page
  const footerY = 32;
  page.drawLine({
    start: { x: margin, y: footerY + 12 },
    end: { x: pageWidth - margin, y: footerY + 12 },
    thickness: 0.5,
    color: rgb(0.8, 0.8, 0.8),
  });

  page.drawText(
    'Generated by NigamSetu Civic AI Platform • Verifiable Statutory Grievance Record',
    {
      x: margin,
      y: footerY,
      size: 7.5,
      font: fontRegular,
      color: rgb(0.55, 0.55, 0.55),
    }
  );

  return await pdfDoc.save();
}
